export type DetailLevel = keyof typeof DETAIL_INSTRUCTIONS;

// ── 组装 ────────────────────────────────────────────────────

export const DEFAULT_DETAIL: DetailLevel = 'standard';

export function buildSystemPrompt(
  opts: { detail?: DetailLevel } = {},
): string {
  const detail = opts.detail ?? DEFAULT_DETAIL;
  return [
    SYSTEM_ROLE,
    SCHOOL_CONTEXT,
    CORE_RULES,
    READABILITY_RULES,
    INTERPRETATION_FOCUS,
    CITATION_RULES,
    FALLBACK_RULE,
    DETAIL_INSTRUCTIONS[detail],
  ].join('\n\n');
}

/** 主题模板作为用户消息的一部分注入，不塞进 system，便于按问题切换。 */
export function buildTopicInstruction(topic?: TopicKey): string {
  if (!topic) return '';
  const template = TOPIC_TEMPLATES[topic];
  return template ? `请按以下结构输出：\n${template}` : '';
}

